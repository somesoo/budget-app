#!/usr/bin/env node
/*
 * Keeps the translations in step with the English source (src/locales/en).
 *
 *   npm run i18n          sync every language, then report what's untranslated
 *   npm run i18n -- --check   report only; exits 1 if a file is out of sync
 *
 * Syncing, for every other language directory in src/locales:
 *   - adds keys English has and the language lacks, empty (the app shows
 *     English until they're filled in), and drops keys English no longer has
 *   - copies each key's "context" from English, so a translator always sees it
 *   - gives plural keys exactly the forms the language needs (Polish: one,
 *     few, many, other), keeping what's already translated
 *   - orders keys like English
 * and regenerates src/locales/index.ts, which imports every file.
 */
import { existsSync, readFileSync, readdirSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'
import { fileURLToPath } from 'node:url'

const ROOT = fileURLToPath(new URL('../src/locales/', import.meta.url))
const SOURCE = 'en'
const check = process.argv.includes('--check')

const isLeaf = (node) => node && typeof node === 'object' && 'context' in node
const readJson = (path) => JSON.parse(readFileSync(path, 'utf8'))
const toJson = (value) => JSON.stringify(value, null, 2) + '\n'

const languages = readdirSync(ROOT, { withFileTypes: true })
  .filter((d) => d.isDirectory())
  .map((d) => d.name)
  .sort((a, b) => (a === SOURCE ? -1 : b === SOURCE ? 1 : a.localeCompare(b)))
const namespaces = readdirSync(join(ROOT, SOURCE))
  .filter((f) => f.endsWith('.json'))
  .map((f) => f.slice(0, -5))
  .sort()

const CLDR_ORDER = ['zero', 'one', 'two', 'few', 'many', 'other']
const pluralForms = (language) =>
  new Intl.PluralRules(language)
    .resolvedOptions()
    .pluralCategories.sort((a, b) => CLDR_ORDER.indexOf(a) - CLDR_ORDER.indexOf(b))

function syncNode(source, target, language, path, report) {
  const out = {}
  for (const [key, node] of Object.entries(source)) {
    const at = path ? `${path}.${key}` : key
    const existing = target && typeof target === 'object' ? target[key] : undefined
    if (!isLeaf(node)) {
      out[key] = syncNode(node, existing, language, at, report)
      continue
    }
    const leaf = {}
    if ('message' in node) {
      leaf.message = typeof existing?.message === 'string' ? existing.message : ''
      if (!leaf.message) report.push(at)
    } else {
      for (const form of pluralForms(language)) {
        leaf[form] = typeof existing?.[form] === 'string' ? existing[form] : ''
        if (!leaf[form]) report.push(`${at} (${form})`)
      }
    }
    leaf.context = node.context
    out[key] = leaf
  }
  return out
}

let outOfSync = false
let untranslated = 0

for (const language of languages.filter((l) => l !== SOURCE)) {
  for (const ns of namespaces) {
    const source = readJson(join(ROOT, SOURCE, `${ns}.json`))
    const path = join(ROOT, language, `${ns}.json`)
    const before = existsSync(path) ? readFileSync(path, 'utf8') : ''
    const report = []
    const synced = toJson(syncNode(source, before ? JSON.parse(before) : {}, language, '', report))
    if (synced !== before) {
      outOfSync = true
      if (!check) writeFileSync(path, synced)
      console.log(`${check ? 'out of sync' : 'synced'}: ${language}/${ns}.json`)
    }
    untranslated += report.length
    for (const key of report) console.log(`  untranslated ${language}: ${ns}.${key}`)
  }
  for (const f of readdirSync(join(ROOT, language))) {
    if (f.endsWith('.json') && !namespaces.includes(f.slice(0, -5)))
      console.log(`  ${language}/${f} has no English source; remove it or add en/${f}`)
  }
}

/* ---------- src/locales/index.ts ---------- */

const ident = (language, ns) => `${language}_${ns.replace(/\W/g, '_')}`
const index = [
  '// Generated by scripts/i18n.mjs (npm run i18n): do not edit by hand.',
  '',
  ...languages.flatMap((language) =>
    namespaces.map((ns) => `import ${ident(language, ns)} from './${language}/${ns}.json'`),
  ),
  '',
  ...languages.map(
    (language) =>
      `const ${language} = {\n${namespaces.map((ns) => `  ${ns}: ${ident(language, ns)},`).join('\n')}\n}`,
  ),
  '',
  `/** The English files, the source every key and its context comes from. */`,
  `export type Messages = typeof ${SOURCE}`,
  '',
  `export const MESSAGES: Record<string, unknown> = { ${languages.join(', ')} }`,
  '',
].join('\n')
const indexPath = join(ROOT, 'index.ts')
if (!existsSync(indexPath) || readFileSync(indexPath, 'utf8') !== index) {
  outOfSync = true
  if (!check) writeFileSync(indexPath, index)
  console.log(`${check ? 'out of sync' : 'written'}: src/locales/index.ts`)
}

console.log(untranslated ? `${untranslated} untranslated` : 'Every language is complete.')
if (check && outOfSync) {
  console.log('Run `npm run i18n` to sync.')
  process.exit(1)
}
